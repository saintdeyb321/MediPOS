using System.Runtime.InteropServices;
using System.Text.Json;
using Npgsql;

namespace MediPOS.Performance;

public static class Program
{
    private static readonly JsonSerializerOptions JsonOptions = new() { WriteIndented = true };
    public static async Task<int> Main(string[] args)
    {
        using var cancellation = new CancellationTokenSource();
        Console.CancelKeyPress += (_, eventArgs) => { eventArgs.Cancel = true; cancellation.Cancel(); };
        try
        {
            var cleanup = args.Length > 0 && args[0] == "cleanup";
            var options = PerformanceOptions.Parse(cleanup ? args[1..] : args);
            if (cleanup)
            {
                await DisposablePerformanceDatabase.CleanupAsync(options, cancellation.Token).ConfigureAwait(false);
                Console.WriteLine("Marked disposable database removed.");
                return 0;
            }
            // Output directory is validated before any connection, and receives no credential/SQL parameters.
            Directory.CreateDirectory(options.OutputDirectory);
            var output = Path.Combine(options.OutputDirectory, options.RunId + ".json");
            var started = DateTimeOffset.UtcNow;
            await using var database = await DisposablePerformanceDatabase.CreateAsync(options, cancellation.Token).ConfigureAwait(false);
            using var observation = new PerformanceObservation();
            await using var dataset = new PerformanceDataset(options, database, observation);
            Console.WriteLine($"Preparing disposable run {options.RunId}; target=NOT_MEASURED");
            await dataset.GenerateAsync(cancellation.Token).ConfigureAwait(false);
            var runner = new PerformanceRunner(options, dataset);
            var allocatedBefore = GC.GetTotalAllocatedBytes();
            var completed = false;
            try
            {
                await runner.RunAsync(cancellation.Token).ConfigureAwait(false);
                completed = true;
            }
            finally
            {
                var connection = new NpgsqlConnectionStringBuilder(database.RuntimeConnection);
                var report = new
                {
                    ScenarioVersion = PerformanceOptions.ScenarioVersion,
                    options.RunId,
                    StartedUtc = started,
                    FinishedUtc = DateTimeOffset.UtcNow,
                    Configuration = options,
                    Measurement = new
                    {
                        Kind = "internal-handler; NOT HTTP end-to-end",
                        Clock = "Stopwatch monotonic",
                        Percentiles = "nearest-rank: sorted[ceil(p*n)-1]; success/conflict/error reported separately",
                        Throughput = "operations / sum of released batch windows; preparation, validation and disposal excluded; closed-loop load",
                        Phases = "inclusive nested activities; do not sum overlapping phases; SQL excludes full reader materialization, manual tenant GUC/SET commands and commit",
                        Connections = "observed logical runtime checkouts; opening includes pool/network wait and mandatory runtime role guard; not total server/pool utilization",
                        Warmup = "excluded from latency/throughput; mutations retained as legitimate synthetic history",
                        BusinessClockUtc = PerformanceDataset.BusinessTime,
                        DatasetDeterminism = "content/order by seed; UUIDv7 IDs generated by domain factories",
                        HttpTarget = "NOT_MEASURED",
                        Integrity = completed ? "per-sale payments/movements/audits/commissions and final ledger checked outside measured windows" : "NOT_VALIDATED: workload incomplete; only prior per-operation checks may have completed",
                    },
                    Environment = new
                    {
                        options.EnvironmentLabel,
                        options.ServerHardware,
                        database.PostgreSqlVersion,
                        PostgreSqlSettings = database.Settings,
                        Runtime = RuntimeInformation.FrameworkDescription,
                        ClientOs = RuntimeInformation.OSDescription,
                        ClientCpuCount = System.Environment.ProcessorCount,
                        ClientMemoryBytes = GC.GetGCMemoryInfo().TotalAvailableMemoryBytes,
                        connection.MaxPoolSize,
                        connection.Timeout,
                        connection.CommandTimeout,
                        connection.Multiplexing,
                        ProcessWorkingSetBytes = System.Environment.WorkingSet,
                        HarnessAllocationBytesIncludingUntimedPreparation = GC.GetTotalAllocatedBytes() - allocatedBefore,
                    },
                    Completed = completed,
                    Results = completed ? runner.Results : runner.Results.Select(result => result with { TargetResult = "NOT_MEASURED" }).ToArray(),
                    SearchTarget = !completed ? "NOT_MEASURED" : Aggregate(runner.Results.Where(result => result.TargetMilliseconds == 500)),
                    ConfirmationTarget = !completed ? "NOT_MEASURED" : Aggregate(runner.Results.Where(result => result.TargetMilliseconds == 1000)),
                };
                await File.WriteAllTextAsync(output, JsonSerializer.Serialize(report, JsonOptions), CancellationToken.None).ConfigureAwait(false);
                Console.WriteLine("Structured results written outside the workspace.");
            }
            if (options.Explain)
            {
                var plans = await observation.ExplainAsync(database.RuntimeConnection, cancellation.Token).ConfigureAwait(false);
                await File.WriteAllTextAsync(Path.Combine(options.OutputDirectory, options.RunId + ".explain.json"),
                    JsonSerializer.Serialize(plans, JsonOptions), cancellation.Token).ConfigureAwait(false);
            }
            return runner.Results.Any(result => result.Errors != 0 || result.TargetResult == "FAIL") ? 1 : 0;
        }
        catch (Exception error) when (error is not OutOfMemoryException)
        {
            // Connection exceptions may contain endpoint/credentials/SQL. Never print their Message/ToString.
            Console.Error.WriteLine("Performance execution stopped: " + error.GetType().Name + ". Check structured workload completion; incomplete workloads cannot approve a latency target.");
            return 2;
        }
    }

    public static string Aggregate(IEnumerable<ScenarioResult> results)
    {
        var statuses = results.Select(result => result.TargetResult).ToArray();
        return statuses.Any(status => status == "FAIL") ? "FAIL" :
            statuses.Length == 0 || statuses.Any(status => status == "NOT_MEASURED") ? "NOT_MEASURED" : "PASS";
    }
}
