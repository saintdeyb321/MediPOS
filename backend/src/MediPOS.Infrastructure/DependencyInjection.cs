    public static IServiceCollection AddInfrastructure(
        this IServiceCollection services,
        IConfiguration configuration)
    {
        var connectionString = configuration.GetConnectionString("MediPosDatabase");

        if (string.IsNullOrWhiteSpace(connectionString))
        {
            throw new InvalidOperationException(
                "Configure 'ConnectionStrings:MediPosDatabase' using environment variables or User Secrets.");
        }

        NpgsqlConnectionStringBuilder runtimeConnection;
        try { runtimeConnection = new NpgsqlConnectionStringBuilder(connectionString); }
        catch (ArgumentException) { throw new InvalidOperationException("The operational database configuration is invalid."); }
        if (runtimeConnection.Multiplexing)
            throw new InvalidOperationException("Multiplexing is incompatible with connection-scoped tenant isolation.");
        services.AddDbContext<MediPosDbContext>(options => options.UseNpgsql(connectionString)
            .AddInterceptors(new RuntimeDatabaseRoleInterceptor()));
        services.AddScoped<ITenantDataContext, TenantDataContext>();
        services.TryAddScoped<IPlatformAdministration, DisabledPlatformAdministration>();
        services.TryAddScoped<ITenantOperationAuthorizer, DisabledTenantOperationAuthorizer>();
        services.TryAddSingleton(TimeProvider.System);
        services.AddLogging();
        services.AddScoped<NotificationStore>();
        services.AddScoped<ISyncDeviceStore, SyncDeviceStore>();
        services.AddScoped<ISyncDeviceDirectory, SyncDeviceDirectory>();
        services.AddScoped<ISyncEventInbox, SyncEventInbox>();
        services.AddScoped<IBranchCatalogSyncReader, BranchCatalogSyncReader>();
        services.AddScoped<IOfflineSaleConflictStore, OfflineSaleConflictStore>();
        services.AddScoped<IOfflineSaleCheckoutTransaction, SaleCheckoutTransaction>();
        services.AddScoped<INotificationReader>(provider => provider.GetRequiredService<NotificationStore>());
        services.AddScoped<INotificationReadWriter>(provider => provider.GetRequiredService<NotificationStore>());
        services.AddScoped<IExpirationAlertsStore, ExpirationAlertsStore>();
        services.AddScoped<GenerateTenantExpirationAlerts>();
        services.AddSingleton<IExpirationAlertsSystem, ExpirationAlertsSystem>();
        services.AddSingleton<RunExpirationAlertsJob>();
        var expirationScheduler = configuration["Notifications:ExpirationAlerts:Enabled"];
        if (expirationScheduler is not null && !bool.TryParse(expirationScheduler, out _))
            throw new InvalidOperationException("Notifications:ExpirationAlerts:Enabled must be true or false.");
        if (string.Equals(expirationScheduler, "true", StringComparison.OrdinalIgnoreCase))
            services.AddHostedService<ExpirationAlertsScheduler>();
        services.AddScoped<ITenancyLicensingStore, TenancyLicensingStore>();
        services.AddScoped<IPlatformDirectoryReader, PlatformDirectoryReader>();
        services.AddScoped<PlatformDirectoryQueries>();
        services.AddScoped<CreateTenantHandler>();
        services.AddScoped<ITenantCreationRequests, TenantCreationRequests>();
        services.AddScoped<CreateTenantIdempotentlyHandler>();
        services.AddScoped<RenewLicenseHandler>();
        services.AddScoped<SuspendLicenseHandler>();
        services.AddScoped<ReactivateLicenseHandler>();
        services.AddScoped<RequestTenantPurgeHandler>();
        services.AddScoped<ITenantLicenseProvisioning, TenantLicenseProvisioning>();
        services.AddScoped<IBranchesStore, BranchesStore>();
        services.AddScoped<IBranchDirectoryReader, BranchDirectoryReader>();
        services.AddScoped<MediPOS.Application.Modules.AuditSupport.IAuditHistoryReader, MediPOS.Infrastructure.Modules.AuditSupport.Persistence.AuditHistoryReader>();
        services.AddScoped<MediPOS.Application.Modules.AuditSupport.GetAuditHistoryHandler>();
        services.AddScoped<BranchDirectoryQueries>();
        services.AddScoped<CreateLegalEntityHandler>();
        services.AddScoped<CreateBranchHandler>();
        services.AddScoped<SetMainHubBranchHandler>();
        services.AddScoped<IIdentityAccessStore, IdentityAccessStore>();
        services.AddScoped<MediPOS.Application.Modules.IdentityAccess.Directory.IMyTenantDirectoryReader, MyTenantDirectoryReader>();
        services.AddScoped<MediPOS.Application.Modules.IdentityAccess.Directory.IEmployeeDirectoryReader, EmployeeDirectoryReader>();
        services.AddScoped<MediPOS.Application.Modules.IdentityAccess.Directory.EmployeeDirectoryQueries>();
        services.AddScoped<IOperationalAccessReader, OperationalAccessReader>();
        services.AddScoped<IOpenCashSessionWriter, OpenCashSessionWriter>();
        services.AddScoped<IFindOpenCashSession, CashSessionReader>();
        services.AddScoped<IActiveCashSessionsReader, CashSessionReader>();
        services.AddScoped<ICashCloseTransaction, CashCloseTransaction>();
        services.AddScoped<ICashSessionReconciliationReader, CashSessionReconciliationReader>();
        services.AddScoped<ICashTransferReader, CashTransferReader>();
        services.AddScoped<IOwnerBranchOverviewReader, OwnerBranchOverviewReader>();
        services.AddScoped<IOwnerCommissionsReportReader, OwnerCommissionsReportReader>();
        services.AddScoped<IReportExportReader, ReportExportReader>();
        services.AddScoped<IReportDocumentRenderer, ReportDocumentRenderer>();
        var exportTimeout = configuration["Reporting:Exports:TimeoutSeconds"];
        var timeout = exportTimeout is null ? 30 : int.Parse(exportTimeout, System.Globalization.CultureInfo.InvariantCulture);
        if (timeout is < 1 or > 300) throw new InvalidOperationException("Reporting:Exports:TimeoutSeconds must be between 1 and 300.");
        services.AddSingleton(new ReportExportLimits { Timeout = TimeSpan.FromSeconds(timeout) });
        services.AddScoped<IOwnerOperationalDashboardReader, OwnerOperationalDashboardReader>();
        services.AddScoped<IOwnerSalesReportReader, OwnerSalesReportReader>();
        services.AddScoped<IOwnerInventoryRiskReader, OwnerInventoryRiskReader>();
        services.AddScoped<IOwnerProductRotationReader, OwnerProductRotationReader>();
        services.AddScoped<IOwnerReplenishmentReader, OwnerReplenishmentReader>();
